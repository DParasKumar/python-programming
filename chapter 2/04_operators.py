# Arithmetic Operators
a = 34
b = 5
c = a + b
print(c)

# Assignment Operators
a = 4-2 #assigning the value of 4-2 to a
print(a)
b = 6
b +=3 #increment the value of b by 3 and then assign the new value to b
b -=3
print(b)

# Comparison Operators
d = 5<4
d = 5<=4
d = 5>4
d = 5>=4
d = 5==4
d = 5!=4
print(d)

# Logical Operators
e = True and False
e = True or False
print(e)

# Truth table of'or' operator
print(True or True)
print(True or False)
print(False or True)
print(False or False)

# truth table of 'and' operator
print(True and True)
print(True and False)
print(False and True)
print(False and False)

# truth table of 'not' operator
print(not True)
print(not False)